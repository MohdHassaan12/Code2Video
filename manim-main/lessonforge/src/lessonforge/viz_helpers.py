# --- Custom Universal TTS Voiceover Service (with dynamic multi-provider routing) ---

class UniversalTTSService(SpeechService):
    def __init__(self, api_key=None, speaker="shubh", model="bulbul:v3", language=None,
                 provider=None, tts_model=None, **kwargs):
        initialize_speech_service(self, kwargs)
        self.api_key = api_key or os.getenv("SARVAM_AI_KEY")
        self.speaker = speaker
        self.model = model  # Sarvam model (e.g. "bulbul:v3")
        # Language: explicit arg > TTS_LANGUAGE env > default en-IN
        self.language = language or os.getenv("TTS_LANGUAGE") or "en-IN"
        # Provider: explicit arg > tts_provider in kwargs > TTS_PROVIDER env > default sarvam
        self.provider = (provider or kwargs.get("tts_provider") or os.getenv("TTS_PROVIDER", "sarvam")).lower()
        logger.info(
            f"UniversalTTSService: provider={self.provider} lang={self.language} "
            f"speaker={self.speaker}"
        )

        self.delegate = None
        if self.provider == "gemini":
            # tts_model arg > GEMINI_TTS_MODEL env > default
            effective_model = tts_model or os.getenv("GEMINI_TTS_MODEL", "google/gemini-3.1-flash-tts-preview")
            voice = self.speaker if self.speaker and self.speaker in GEMINI_VOICES else os.getenv("GEMINI_TTS_VOICE", "Puck")
            logger.info(f"Routing speech to Gemini TTS: model={effective_model} voice={voice} lang={self.language}")
            self.delegate = GeminiTTSService(voice_name=voice, language=self.language, model=effective_model)
        elif self.provider == "edge":
            logger.info(f"Routing speech to Edge TTS: voice={self.speaker} lang={self.language}")
            self.delegate = EdgeTTSService(voice_name=self.speaker, language=self.language)
        elif self.provider in ("local", "kokoro"):
            logger.info(f"Routing speech to Local Kokoro TTS: voice={self.speaker} lang={self.language}")
            self.delegate = LocalTTSService(voice_name=self.speaker, language=self.language)

    def _shared_key(self, text: str) -> str:
        """Content-address of the request INTENT: the provider config that shapes
        the audio plus the raw cue text (pacing tags included — they change pace/
        SSML). Keyed on intent, not on which provider ultimately fulfilled it, so
        a fallback-synthesized clip still satisfies identical future requests —
        the same semantics as a failover chain's cache."""
        if self.delegate is not None:
            if isinstance(self.delegate, GeminiTTSService):
                cfg = {"provider": "gemini", "model": self.delegate.model,
                       "voice": self.delegate.voice_name, "language": self.language}
            elif isinstance(self.delegate, EdgeTTSService):
                cfg = {"provider": "edge", "voice": self.delegate.voice_name,
                       "language": self.language, "rate": self.delegate.rate}
            elif isinstance(self.delegate, LocalTTSService):
                cfg = {"provider": "local", "voice": self.delegate.voice_name,
                       "language": self.language, "speed": self.delegate.speed}
            else:
                cfg = {"provider": self.provider, "speaker": self.speaker, "language": self.language}
        else:
            cfg = {"provider": "sarvam", "model": self.model,
                   "speaker": self.speaker, "language": self.language}
        ident = json.dumps({"v": 1, **cfg, "text": text}, sort_keys=True, ensure_ascii=False)
        return hashlib.sha256(ident.encode("utf-8")).hexdigest()[:32]

    def generate_from_text(self, text, cache_dir=None, path=None, **kwargs):
        effective_cache = cache_dir if cache_dir is not None else self.cache_dir

        if _tts_muted():
            # Visuals-only render (TTS_MUTE=1): silence sized to the narration, so
            # beat length — and therefore sustain, entrance pacing and every layout
            # measurement — behaves exactly as it does with real audio, at zero cost.
            #
            # The shared cache is deliberately NEITHER read NOR written here. Its key
            # is the request INTENT (provider config + text) and does not record which
            # tier answered — by design, so a fallback clip satisfies later requests.
            # Storing silence under that key would make the NEXT real render silent,
            # turning a money-saving test flag into a poisoned cache that is hard to
            # trace back. Muting must cost nothing and leave nothing behind.
            result = self._generate_silence(text, effective_cache, path)
            _tts_degraded("muted", "TTS_MUTE=1 — visuals-only render, NO narration")
            return result

        shared = _shared_tts_cache_dir()
        key = self._shared_key(text) if shared is not None else None
        if key is not None:
            hit = _shared_tts_lookup(shared, key, effective_cache, path)
            if hit is not None:
                logger.info(f"Shared TTS cache hit ({key[:8]}…) — no synthesis billed.")
                return hit
        result = self._synthesize(text, effective_cache, path, **kwargs)
        if key is not None and isinstance(result, dict):
            _shared_tts_store(shared, key, result, effective_cache)
        return result

    def _synthesize(self, text, effective_cache, path=None, **kwargs):
        """Provider chain: primary → Gemini (keyed) → gTTS (KEYLESS) → silence (opt-in).

        Each tier is louder than the last: every non-primary tier prints a
        ``TTS_DEGRADED:`` marker the server counts into the sidecar, so a video that
        shipped on a degraded voice is never mistaken for a clean one. The keyless
        tier exists because a provider outage used to kill an entire render
        (2026-07-21) — a worse-sounding video beats no video, but only if the
        degradation is visible.
        """
        try:
            if self.delegate is not None:
                return self.delegate.generate_from_text(text, cache_dir=effective_cache, path=path, **kwargs)
            else:
                return self._generate_sarvam_direct(text, effective_cache, path, **kwargs)
        except Exception as primary_err:
            logger.warning(f"Primary TTS provider failed: {primary_err}. Attempting fallback to Gemini TTS...")

            # Fallback 1: Gemini TTS (OpenRouter, keyed)
            gemini_err = None
            if self.delegate is None:
                try:
                    gemini_service = GeminiTTSService(
                        api_key=os.getenv("OPENROUTER_API_KEY"),
                        voice_name=self.speaker if self.speaker and self.speaker in GEMINI_VOICES else os.getenv("GEMINI_TTS_VOICE", "Puck"),
                        language=self.language,
                        cache_dir=effective_cache
                    )
                    result = gemini_service.generate_from_text(text, cache_dir=effective_cache, path=path, **kwargs)
                    if _tts_config_absent(primary_err):
                        # Configured routing, not degradation (no Sarvam key on this box).
                        logger.info("Primary TTS provider not configured; Gemini is the "
                                    "configured voice for this deployment.")
                    else:
                        _tts_degraded("gemini-fallback",
                                      f"primary failed: {str(primary_err)[:120]}")
                    return result
                except Exception as err:
                    gemini_err = err
                    logger.error(f"Gemini TTS fallback failed: {err}.")
            else:
                # The primary WAS Gemini; retrying the same dead endpoint is pointless.
                gemini_err = primary_err

            # Fallback 2: gTTS — KEYLESS. Different vendor, different network path, so a
            # keyed-provider outage cannot take it down with them. Degraded voice, real speech.
            if os.getenv("TTS_KEYLESS_FALLBACK", "1") == "1":
                try:
                    result = self._generate_gtts_keyless(text, effective_cache, path)
                    _tts_degraded("gtts-keyless",
                                  f"keyed providers failed: {str(gemini_err)[:120]}")
                    return result
                except Exception as gtts_err:
                    logger.error(f"Keyless gTTS fallback failed: {gtts_err}.")

            # Fallback 3: silence, sized to the text. OFF by default — shipping silent
            # narration unflagged would be worse than failing loudly (a render that
            # fails is retried; a silent video gets published).
            if os.getenv("TTS_SILENT_FALLBACK", "0") == "1":
                try:
                    result = self._generate_silence(text, effective_cache, path)
                    _tts_degraded("silence", "ALL voice providers failed — video has NO narration")
                    return result
                except Exception as silence_err:
                    logger.error(f"Silent fallback failed: {silence_err}.")

            raise RuntimeError(f"All TTS services failed. Primary: {primary_err}, Gemini: {gemini_err}")

    def _clean_for_speech(self, text):
        """Strip bookmarks + pacing tags — shared by the keyless/silent tiers."""
        out = remove_bookmarks(text)
        out = re.sub(r'\[SPEED:\s*.*?\]', '', out, flags=re.IGNORECASE)
        out = re.sub(r'\[PAUSE.*?\]', '', out, flags=re.IGNORECASE)
        return out.strip()

    def _generate_gtts_keyless(self, text, cache_dir, path=None):
        """Last-resort KEYLESS synthesis via the real gTTS package.

        Imports `gtts` directly on purpose: this module monkeypatches
        `manim_voiceover.services.gtts.GTTSService` to route back through
        UniversalTTSService, so going through manim_voiceover here would recurse
        into the failing chain instead of reaching Google Translate's endpoint.
        """
        from gtts import gTTS  # real package, NOT the monkeypatched service

        input_text = self._clean_for_speech(text)
        if not input_text:
            raise ValueError("nothing to speak after tag stripping")
        lang = (self.language or "en").split("-")[0].lower()
        input_data = {"input_text": input_text, "service": "gtts-keyless",
                      "language": lang}
        cached_result = self.get_cached_result(input_data, cache_dir)
        if cached_result is not None:
            return cached_result
        audio_path = (self.get_audio_basename(input_data) + ".mp3") if path is None \
            else path_to_string(path)
        try:
            gTTS(text=input_text, lang=lang).save(str(Path(cache_dir) / audio_path))
        except Exception:
            # An unsupported locale must not be the reason narration dies.
            gTTS(text=input_text, lang="en").save(str(Path(cache_dir) / audio_path))
        return {"input_text": text, "input_data": input_data,
                "original_audio": audio_path}

    def _generate_silence(self, text, cache_dir, path=None):
        """Emergency: silence sized to the narration so beat timing survives."""
        import wave

        input_text = self._clean_for_speech(text)
        words = max(1, len(input_text.split()))
        seconds = max(1.0, words / 150.0 * 60.0)  # 150 wpm reading pace
        input_data = {"input_text": input_text, "service": "silence",
                      "language": self.language}
        cached_result = self.get_cached_result(input_data, cache_dir)
        if cached_result is not None:
            return cached_result
        audio_path = (self.get_audio_basename(input_data) + ".wav") if path is None \
            else path_to_string(path)
        with wave.open(str(Path(cache_dir) / audio_path), "wb") as wav_file:
            wav_file.setnchannels(1)
            wav_file.setsampwidth(2)
            wav_file.setframerate(24000)
            wav_file.writeframes(b"\x00\x00" * int(24000 * seconds))
        return {"input_text": text, "input_data": input_data,
                "original_audio": audio_path}

    def _generate_sarvam_direct(self, text, cache_dir, path, **kwargs):
        input_text = remove_bookmarks(text)
        
        # Parse educational pacing tags
        pace = 1.0
        if re.search(r'\[SPEED:\s*SPRINT\]', input_text, flags=re.IGNORECASE):
            pace = 1.15
        elif re.search(r'\[SPEED:\s*STROLL\]', input_text, flags=re.IGNORECASE):
            pace = 0.85
            
        # Strip all tags
        input_text = re.sub(r'\[SPEED:\s*.*?\]', '', input_text, flags=re.IGNORECASE)
        input_text = re.sub(r'\[PAUSE.*?\]', '', input_text, flags=re.IGNORECASE)
        input_text = input_text.strip()
        
        if self.language:
            target_lang = self.language
        else:
            target_lang = "en-US"

        input_data = {
            "input_text": input_text,
            "service": "sarvam",
            "speaker": self.speaker,
            "language": target_lang
        }

        cached_result = self.get_cached_result(input_data, cache_dir)
        if cached_result is not None:
            return cached_result

        if path is None:
            audio_path = self.get_audio_basename(input_data) + ".wav"
        else:
            audio_path = path_to_string(path)

        if not self.api_key:
            raise ValueError("SARVAM_AI_KEY is required for UniversalTTSService. Please configure it in your environment.")

        url = "https://api.sarvam.ai/text-to-speech"
        headers = {
            "api-subscription-key": self.api_key,
            "Content-Type": "application/json"
        }
        payload = {
            "text": input_text,
            "target_language_code": target_lang,
            "speaker": self.speaker,
            "model": self.model,
            "pace": pace
        }

        logger.info(f"Generating Sarvam TTS audio for text of length {len(input_text)} in {target_lang}")
        response = requests.post(url, json=payload, headers=headers, timeout=60)
        response.raise_for_status()

        data = response.json()
        audio_b64 = data["audios"][0]
        audio_bytes = base64.b64decode(audio_b64)

        full_path = Path(cache_dir) / audio_path
        with open(full_path, "wb") as f:
            f.write(audio_bytes)

        json_dict = {
            "input_text": text,
            "input_data": input_data,
            "original_audio": audio_path,
        }

        return json_dict


