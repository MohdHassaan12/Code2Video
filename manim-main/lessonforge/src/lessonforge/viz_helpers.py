def _bg_image(scene):
    """Return the background image mobject, or None. Guarded so missing attrs never crash."""
    cam = getattr(scene, "camera", None)
    return getattr(cam, "background_image", None) if cam is not None else None


def _clamp_width(mobj, max_w=None):
    """Scale a mobject DOWN (never up) so its width fits max_w (default SAFE_W)."""
    max_w = max_w or SAFE_W
    try:
        if mobj.width > max_w and mobj.width > 0:
            mobj.scale_to_fit_width(max_w)
    except Exception:
        pass  # layout guard must never crash a render
    return mobj
