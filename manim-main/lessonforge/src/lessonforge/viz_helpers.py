def generate_adaptive_native_fallback(keyword: str, color, height: float) -> VGroup:
    """
    Constructs an adaptive, stylized native Manim mobject vector graphic matching
    the keyword domain, to prevent plain placeholder error boxes when offline or APIs fail.
    """
    keyword_clean = keyword.lower().strip()
    
    # 1. "car" / "vehicle"
    if any(k in keyword_clean for k in ["car", "vehicle", "truck", "automobile"]):
        chassis = RoundedRectangle(corner_radius=height * 0.15, height=height * 0.4, width=height * 1.0, color=color, fill_opacity=0.3)
        cabin = RoundedRectangle(corner_radius=height * 0.1, height=height * 0.3, width=height * 0.6, color=color, fill_opacity=0.3)
        cabin.next_to(chassis, UP, buff=0).shift(LEFT * height * 0.1)
        wheel_l = Circle(radius=height * 0.15, color=color, fill_opacity=0.8).move_to(chassis.get_corner(DL) + RIGHT * height * 0.25)
        wheel_r = Circle(radius=height * 0.15, color=color, fill_opacity=0.8).move_to(chassis.get_corner(DR) + LEFT * height * 0.25)
        return VGroup(chassis, cabin, wheel_l, wheel_r)
        
    # 2. "building" / "house"
    elif any(k in keyword_clean for k in ["building", "house", "tower", "home"]):
        roof = Triangle(color=color, fill_opacity=0.5).scale(height * 0.35)
        base = Rectangle(height=height * 0.6, width=height * 0.8, color=color, fill_opacity=0.3)
        base.next_to(roof, DOWN, buff=0)
        door = Rectangle(height=height * 0.25, width=height * 0.18, color=color, fill_opacity=0.7)
        door.move_to(base.get_bottom() + UP * height * 0.125)
        return VGroup(roof, base, door)
        
    # 3. "arrow" / "force" / "vector"
    elif any(k in keyword_clean for k in ["arrow", "force", "vector", "velocity", "acceleration"]):
        arr = Arrow(LEFT * height * 0.75, RIGHT * height * 0.75, color=color, stroke_width=4, buff=0)
        return VGroup(arr)
        
    # 4. "cell" / "atom" / "nucleus"
    elif any(k in keyword_clean for k in ["cell", "atom", "nucleus", "molecule"]):
        nucleus = Dot(point=ORIGIN, radius=height * 0.15, color=color)
        orbit1 = Circle(radius=height * 0.4, color=color, stroke_width=1.5).scale(0.7)
        orbit2 = Circle(radius=height * 0.7, color=color, stroke_width=1.5).scale(0.8)
        e1 = Dot(point=orbit1.point_from_proportion(0.25), radius=height * 0.05, color=color)
        e2 = Dot(point=orbit2.point_from_proportion(0.75), radius=height * 0.05, color=color)
        return VGroup(nucleus, orbit1, orbit2, e1, e2)
        
    # 5. "graph" / "axis" / "plot" / "coordinate_system"
    elif any(k in keyword_clean for k in ["graph", "axis", "plot", "coordinate_system", "axes"]):
        axes = Axes(
            x_range=[-2, 2, 1],
            y_range=[-2, 2, 1],
            x_length=height * 1.5,
            y_length=height * 1.2,
            axis_config={"color": color, "stroke_width": 2, "include_numbers": False}
        )
        curve = axes.plot(lambda x: 0.5 * x**3 - x, color=color, stroke_width=3)
        return VGroup(axes, curve)
        
    # 6. Generic Noun card
    else:
        label_text = keyword.upper()
        if len(label_text) > 15:
            label_text = label_text[:12] + "..."
        text_mob = Text(label_text, font_size=18, color=color)
        card = RoundedRectangle(
            corner_radius=0.1,
            height=max(height * 0.6, text_mob.height + 0.4),
            width=max(height * 1.2, text_mob.width + 0.6),
            color=color,
            stroke_width=2.5,
            fill_opacity=0.15
        )
        accent = Circle(radius=0.06, color=color, fill_opacity=0.8).move_to(card.get_corner(UL) + DR * 0.15)
        text_mob.move_to(card.get_center())
        return VGroup(card, text_mob, accent)


def _sanitize_svg_for_manim(svg_path: str):
    """
    Strips SVG features that crash or confuse Manim's svgelements parser:
      - <text> / <tspan> nodes (cause parser hangs)
      - <linearGradient> / <radialGradient> (unsupported fill references)
      - <filter> and filter= attributes (blurs, shadows → black rectangles)
      - <clipPath> and clip-path= attributes (hide geometry unexpectedly)
      - <mask> elements
      - fill/stroke="url(#...)" replaced with "currentColor" so shapes stay visible
    """
    try:
        with open(svg_path, "r", encoding="utf-8") as f:
            content = f.read()

        # Strip text/tspan
        content = re.sub(r"<te?xt\b[^>]*>.*?</te?xt>", "", content, flags=re.DOTALL | re.IGNORECASE)
        content = re.sub(r"<te?xt\b[^>]*/>", "", content, flags=re.IGNORECASE)
        content = re.sub(r"<tspan\b[^>]*>.*?</tspan>", "", content, flags=re.DOTALL | re.IGNORECASE)

        # Strip problematic <defs> children (gradients, filters, clipPaths, masks)
        for tag in ("linearGradient", "radialGradient", "filter", "clipPath", "mask", "pattern"):
            content = re.sub(
                rf"<{tag}\b[^>]*>.*?</{tag}>", "", content, flags=re.DOTALL | re.IGNORECASE
            )
            content = re.sub(rf"<{tag}\b[^>]*/?>", "", content, flags=re.IGNORECASE)

        # Replace url(#...) fill/stroke references with white so shapes are visible
        content = re.sub(
            r'(fill|stroke)\s*=\s*"url\(#[^)]+\)"',
            r'\1="white"',
            content, flags=re.IGNORECASE
        )
        content = re.sub(
            r'(fill|stroke)\s*:\s*url\(#[^)]+\)',
            r'\1:white',
            content, flags=re.IGNORECASE
        )

        # Remove filter= and clip-path= attributes from elements
        content = re.sub(r'\s+filter\s*=\s*"[^"]*"', "", content, flags=re.IGNORECASE)
        content = re.sub(r'\s+clip-path\s*=\s*"[^"]*"', "", content, flags=re.IGNORECASE)
        content = re.sub(r'\s+mask\s*=\s*"[^"]*"', "", content, flags=re.IGNORECASE)

        # Clean up empty <defs> blocks left behind
        content = re.sub(r"<defs\s*>\s*</defs>", "", content, flags=re.IGNORECASE)

        with open(svg_path, "w", encoding="utf-8") as f:
            f.write(content)
    except Exception:
        pass


