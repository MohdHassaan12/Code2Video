def _try_wikimedia_bitmap(keyword: str, local_path: str) -> bool:
    """Render-time fallback fetch of a raster (jpg/png) from Wikimedia Commons.
    Normally images are resolved server-side at codegen time (app/assets.py
    resolve_image_elements rewrites the element content to a local path); this
    path only fires when that pass was skipped or failed."""
    try:
        params = {
            "action": "query", "format": "json",
            "generator": "search",
            "gsrsearch": f"filetype:bitmap {keyword}",
            "gsrnamespace": 6, "gsrlimit": 5,
            "prop": "imageinfo", "iiprop": "url|size|mime", "iiurlwidth": 1024,
        }
        res = requests.get("https://commons.wikimedia.org/w/api.php", params=params,
                           headers=_REQ_HEADERS, timeout=8)
        res.raise_for_status()
        pages = res.json().get("query", {}).get("pages", {})
        for page in sorted(pages.values(), key=lambda p: p.get("index", 999)):
            infos = page.get("imageinfo") or []
            if not infos:
                continue
            info = infos[0]
            if info.get("mime") not in ("image/jpeg", "image/png"):
                continue
            url = info.get("thumburl") or info.get("url")
            if not url:
                continue
            dl = requests.get(url, headers=_REQ_HEADERS, timeout=12)
            dl.raise_for_status()
            with open(local_path, "wb") as f:
                f.write(dl.content)
            return True
    except Exception as e:
        print(f"Wikimedia bitmap fetch failed: {e}")
    return False


def fetch_real_image(path_or_query: str, height: float = 3.0) -> Mobject:
    """Load a real raster image (photo/painting/map) as an ImageMobject.

    `path_or_query` is normally an absolute local file path pre-resolved by the
    server; a non-path string is treated as a Wikimedia Commons search query and
    fetched on the fly (cached in temp_renders). Aspect ratio is always
    preserved; the result is clamped to fit the 16:9 stage. Falls back to a
    Text placeholder so a missing image never kills a render."""
    src = (path_or_query or "").strip()
    local_path = src if os.path.isabs(src) and os.path.exists(src) else None
    if local_path is None:
        safe_name = "".join(c if c.isalnum() else "_" for c in src)[:60]
        helper_dir = os.path.dirname(os.path.abspath(__file__))
        temp_dir = helper_dir if os.path.basename(helper_dir) == "temp_renders" \
            else (_workspace("temp_renders") or os.path.join(helper_dir, "temp_renders"))
        os.makedirs(temp_dir, exist_ok=True)
        candidate = os.path.join(temp_dir, f"realimg_{safe_name}.jpg")
        if os.path.exists(candidate) or _try_wikimedia_bitmap(src, candidate):
            local_path = candidate
    if local_path:
        try:
            img = ImageMobject(local_path)
            img.scale_to_fit_height(max(0.5, height))
            # Clamp so a wide painting can't span the whole frame or a tall
            # portrait can't overflow vertically.
            if img.width > 7.0:
                img.scale_to_fit_width(7.0)
            if img.height > 5.5:
                img.scale_to_fit_height(5.5)
            return img
        except Exception as e:
            print(f"fetch_real_image: failed to load {local_path}: {e}")
    label = os.path.splitext(os.path.basename(src))[0][:24] if os.path.isabs(src) else src[:24]
    return Text(label, font_size=28)


# --- Generated simulations: load a verified build/animate module ---------------
#
# The module was written by an LLM and then VERIFIED by app/sim_gen (it runs, it stays
# inside its box, something moves) before the path ever reached a storyboard. Loading
# it here — rather than inlining its source into the generated script — is deliberate:
# the Layout QA Critic and the repair agent rewrite the script, and neither can damage
# code that isn't in it. It is the same reasoning that keeps images as a path.

def simulation(module_path: str, width: float = 6.0, height: float = 4.0) -> Mobject:
    """Build a generated simulation's mobject and attach its animator to it.

    Returns the group with `_sim_animate` set, so `sim_play(group, run_time)` can
    animate it later without re-loading anything. Any failure degrades to a Text
    placeholder — a missing simulation must never kill a render."""
    src = (module_path or "").strip()
    try:
        # The cached module contains ONLY the model's two functions — it is told to
        # import nothing, because app/sim_gen's verification harness supplies the
        # namespace. So this loader must supply exactly the same namespace, or every
        # simulation NameErrors on `Axes` and degrades to a placeholder that looks
        # like a working fallback. (Caught by a real render, 2026-08-15: importlib
        # gave the module empty globals and every simulation silently became a Text.)
        namespace = {}
        exec("from manim import *\nimport numpy as np\nimport math", namespace)
        with open(src, "r", encoding="utf-8") as fh:
            exec(compile(fh.read(), src, "exec"), namespace)
        group = namespace["build"](float(width), float(height))
        if not isinstance(group, Mobject):
            raise TypeError(f"build() returned {type(group).__name__}, not a Mobject")
        # The verifier already checked containment, but a caller may ask for a
        # different box than the one it was verified in.
        if group.width > width * 1.02:
            group.scale_to_fit_width(width)
        if group.height > height * 1.02:
            group.scale_to_fit_height(height)
        group._sim_animate = namespace.get("animate")
        return group
    except Exception as e:
        print(f"simulation: could not load {src}: {e}")
        label = os.path.splitext(os.path.basename(src))[0].replace("sim_", "").replace("_", " ")
        return Text(label[:28] or "simulation", font_size=28)


def drawing(module_path: str, height: float = 1.5) -> Mobject:
    """Load a generated Manim DRAWING and size it to `height` scene units.

    The replacement for `fetch_smart_svg` when the server drew the object itself
    (app/sim_gen.generate_drawing). Same loader as `simulation()` — one module contract,
    two uses — but sized like an icon rather than placed like a diagram."""
    group = simulation(module_path, width=6.0, height=6.0)
    try:
        h = max(0.3, float(height))
        group.scale_to_fit_height(h)
        if group.width > 7.0:
            group.scale_to_fit_width(7.0)
    except Exception as e:
        print(f"drawing: could not size {module_path}: {e}")
    return group


def sim_play(group, run_time: float = 3.0):
    """The Animation that evolves a simulation group, or a harmless no-op.

    Always returns something playable: a scene whose simulation failed to load still
    has a real mobject on screen, and `self.play` must not raise because of it."""
    try:
        animator = getattr(group, "_sim_animate", None)
        rt = max(0.4, float(run_time))
        if animator is not None:
            anim = animator(group, rt)
            if isinstance(anim, Animation):
                return anim
    except Exception as e:
        print(f"sim_play: simulation animation failed ({e}) — holding the frame.")
    # Round-trip (it ends on the starting geometry), so a degraded simulation can
    # never manufacture a layout violation. Same rule as sustain(). Colourless:
    # Indicate's default accent used to tint the whole simulation yellow.
    return emphasize(group, run_time=max(0.4, float(run_time)))


# --- TTS resilience: retry transient provider failures before failing over ---
#
# Measured 2026-07-21: OpenRouter's audio endpoint returned HTTP 500 on a direct probe
# AND "200 OK with an empty body" on the render path. One cue's synthesis failed, that
# scene died, and the whole parallel render fell back to sequential (double the time)
# for what was a seconds-long provider blip. A transient HTTP failure is not a synthesis
# failure — retry it before declaring the provider dead.
_TTS_RETRY_STATUS = {408, 409, 425, 429, 500, 502, 503, 504}


def _tts_retry_attempts():
    try:
        return max(1, int(os.getenv("TTS_RETRY_ATTEMPTS", "3")))
    except (TypeError, ValueError):
        return 3


# A provider that was never configured is not a provider that FAILED. This box has no
# SARVAM key by design (CLAUDE.md: TTS falls back to Gemini), so treating that fallback
# as degradation would make `voice_degraded` nonzero on literally every render — and a
# metric that is always red is a metric nobody reads. Only runtime failures count.
_TTS_ABSENT_CONFIG_MARKERS = (
    "SARVAM_AI_KEY is required",
    "OPENROUTER_API_KEY is not set",
    "is required for UniversalTTSService",
)


def _tts_config_absent(err):
    """True when the primary provider was simply not configured (expected routing)."""
    text = str(err)
    return any(marker in text for marker in _TTS_ABSENT_CONFIG_MARKERS)


def _tts_muted():
    """True when this render must synthesize NO speech at all (`TTS_MUTE=1`).

    For visuals-only iteration: every LLM/provider TTS call is a metered edge, and
    re-rendering the same board a dozen times while tuning layout bills the whole
    narration each time. Muting short-circuits the entire chain — no primary, no
    Gemini, no gTTS — to word-count-sized silence.

    Off by default and LOUD when on: it prints a `TTS_DEGRADED:` marker per cue, so
    the sidecar's `voice_degraded` is non-zero and a muted video can never be
    mistaken for a shippable one. Same reasoning as TTS_SILENT_FALLBACK defaulting
    off — a render that fails gets retried, a silent video gets published.
    """
    return os.getenv("TTS_MUTE", "0") == "1"


def _tts_degraded(kind, detail=""):
    """Emit a parseable marker so the server can count voice degradation from the
    render logs (viz_helpers runs in the manim SUBPROCESS — a module counter here
    cannot reach the job/sidecar, but stdout can). Mirrors LAYOUT_VIOLATION:."""
    line = f"TTS_DEGRADED: {kind} {detail}".strip()
    logger.warning(line)
    try:
        print(line, flush=True)
    except Exception:  # noqa: BLE001 - never let telemetry break a render
        pass


def _tts_post_with_retry(url, headers, payload, timeout=60.0, label="TTS"):
    """POST audio synthesis with bounded retry + linear backoff on transient failures.

    Retries on 408/409/425/429/5xx, on transport errors (timeout/connection reset),
    and on the "200 with empty body" shape — all observed provider blips. Returns the
    response; raises the last error when every attempt fails.
    """
    import httpx

    attempts = _tts_retry_attempts()
    last_err = None
    for attempt in range(1, attempts + 1):
        try:
            response = httpx.post(url, headers=headers, json=payload, timeout=timeout)
            if response.status_code == 200 and response.content:
                if attempt > 1:
                    logger.info(f"{label}: recovered on attempt {attempt}/{attempts}.")
                return response
            if response.status_code == 200:
                last_err = RuntimeError(f"{label}: HTTP 200 with empty audio body")
            elif response.status_code in _TTS_RETRY_STATUS:
                last_err = RuntimeError(f"{label}: HTTP {response.status_code}: {response.text[:200]}")
            else:
                # Non-transient (401 bad key, 400 bad request): fail immediately.
                raise RuntimeError(f"{label}: HTTP {response.status_code}: {response.text[:200]}")
        except httpx.HTTPError as exc:
            last_err = exc
        if attempt < attempts:
            delay = float(os.getenv("TTS_RETRY_BACKOFF", "1.5")) * attempt
            logger.warning(f"{label}: transient failure ({last_err}); retry "
                           f"{attempt + 1}/{attempts} in {delay:.1f}s.")
            time.sleep(delay)
    raise last_err if last_err else RuntimeError(f"{label}: synthesis failed")


