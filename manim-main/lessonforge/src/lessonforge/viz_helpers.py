from contextlib import contextmanager

class SceneManager:
    """Manages scene state and automatically fades out stale mobjects between beats."""
    def __init__(self, scene):
        self.scene = scene

    @contextmanager
    def beat(self, name=""):
        """
        Starts a new storyboard beat.
        Automatically removes any unpinned mobjects currently on the screen.
        To keep a mobject across beats, set `mobject.is_pinned = True`.
        """
        mobs_to_remove = [m for m in self.scene.mobjects if m is not None and not getattr(m, "is_pinned", False)]
        # Filter out background objects
        filtered_mobs = []
        for m in mobs_to_remove:
            if hasattr(m, "z_index") and m.z_index < -50:
                continue
            filtered_mobs.append(m)
            
        if filtered_mobs:
            self.scene.play(FadeOut(Group(*filtered_mobs)))
        yield


