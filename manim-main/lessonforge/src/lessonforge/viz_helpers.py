def _resolve_collisions(scene, buff=0.25, iterations=3):
    """Push apart overlapping mobject bounding boxes — fixes the 'two wide labels
    collide in the middle' case that width-clamping alone can't solve."""
    bg = _bg_image(scene)
    items = [m for m in scene.mobjects
             if m is not bg and getattr(m, "width", 0) > 0 and getattr(m, "height", 0) > 0]
    for _ in range(iterations):
        moved = False
        for i in range(len(items)):
            for j in range(i + 1, len(items)):
                a, b = items[i], items[j]
                try:
                    ax0, ax1 = a.get_left()[0], a.get_right()[0]
                    ay0, ay1 = a.get_bottom()[1], a.get_top()[1]
                    bx0, bx1 = b.get_left()[0], b.get_right()[0]
                    by0, by1 = b.get_bottom()[1], b.get_top()[1]
                    xo = min(ax1, bx1) - max(ax0, bx0)
                    yo = min(ay1, by1) - max(ay0, by0)
                    if xo > 0 and yo > 0:
                        if xo < yo:
                            s = (xo + buff) / 2
                            a.shift(LEFT * s); b.shift(RIGHT * s)
                        else:
                            s = (yo + buff) / 2
                            a.shift(DOWN * s); b.shift(UP * s)
                        moved = True
                except Exception:
                    continue
        if not moved:
            break
    return scene


def auto_fit_scene(scene, width_frac=1.0, height_frac=1.0):
    """Final safety net: (1) clamp oversize mobjects, (2) separate collisions,
    (3) nudge everything inside the frame. Call at end of construct()."""
    max_w, max_h = SAFE_W * width_frac, SAFE_H * height_frac
    bg = _bg_image(scene)
    for m in list(scene.mobjects):
        if m is bg: continue
        try:
            if m.width  > max_w: m.scale_to_fit_width(max_w)
            if m.height > max_h: m.scale_to_fit_height(max_h)
        except Exception: continue
    _resolve_collisions(scene)
    for m in list(scene.mobjects):
        if m is bg: continue
        try:
            r, l, t, b = m.get_right()[0], m.get_left()[0], m.get_top()[1], m.get_bottom()[1]
            if r >  FRAME_W / 2: m.shift(LEFT  * (r - FRAME_W / 2 + 0.1))
            if l < -FRAME_W / 2: m.shift(RIGHT * (-FRAME_W / 2 - l + 0.1))
            if t >  FRAME_H / 2: m.shift(DOWN  * (t - FRAME_H / 2 + 0.1))
            if b < -FRAME_H / 2: m.shift(UP    * (-FRAME_H / 2 - b + 0.1))
        except Exception: continue
    return scene


def clear_canvas(scene, run_time=0.5):
    """Fade out everything except the background so a forgotten FadeOut can't
    orphan objects into the next beat."""
    from manim import FadeOut
    bg = _bg_image(scene)
    movers = [m for m in scene.mobjects if m is not bg]
    if movers:
        scene.play(*[FadeOut(m, shift=DOWN) for m in movers], run_time=run_time)


