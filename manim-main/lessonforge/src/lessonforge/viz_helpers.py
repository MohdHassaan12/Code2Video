class LayoutStage:
    """Provides deterministic screen regions to prevent manual coordinate overlaps."""
    MARGIN = 0.6  # Fixed uniform gap from the edge of the canvas
    
    @staticmethod
    def position_left(mobject):
        mobject.to_edge(LEFT, buff=LayoutStage.MARGIN)
        max_width = config.frame_width / 2 - LayoutStage.MARGIN * 1.5
        max_height = config.frame_height - LayoutStage.MARGIN * 2
        if mobject.width > max_width:
            mobject.scale_to_fit_width(max_width)
        if mobject.height > max_height:
            mobject.scale_to_fit_height(max_height)
        return mobject
        
    @staticmethod
    def position_right(mobject):
        mobject.to_edge(RIGHT, buff=LayoutStage.MARGIN)
        max_width = config.frame_width / 2 - LayoutStage.MARGIN * 1.5
        max_height = config.frame_height - LayoutStage.MARGIN * 2
        if mobject.width > max_width:
            mobject.scale_to_fit_width(max_width)
        if mobject.height > max_height:
            mobject.scale_to_fit_height(max_height)
        return mobject

    @staticmethod
    def fit_to_safe_zone(mobject):
        """Mathematically forces the mobject to stay inside the canvas with a uniform fixed gap."""
        max_width = config.frame_width - LayoutStage.MARGIN * 2
        max_height = config.frame_height - LayoutStage.MARGIN * 2
        
        # Scale down if it's too big
        if mobject.width > max_width:
            mobject.scale_to_fit_width(max_width)
        if mobject.height > max_height:
            mobject.scale_to_fit_height(max_height)
            
        # Shift if it breaches the absolute boundaries
        top_limit = config.frame_height / 2 - LayoutStage.MARGIN
        bottom_limit = -config.frame_height / 2 + LayoutStage.MARGIN
        right_limit = config.frame_width / 2 - LayoutStage.MARGIN
        left_limit = -config.frame_width / 2 + LayoutStage.MARGIN
        
        if mobject.get_top()[1] > top_limit:
            mobject.shift(DOWN * (mobject.get_top()[1] - top_limit))
        if mobject.get_bottom()[1] < bottom_limit:
            mobject.shift(UP * (bottom_limit - mobject.get_bottom()[1]))
        if mobject.get_right()[0] > right_limit:
            mobject.shift(LEFT * (mobject.get_right()[0] - right_limit))
        if mobject.get_left()[0] < left_limit:
            mobject.shift(RIGHT * (left_limit - mobject.get_left()[0]))
            
        return mobject


