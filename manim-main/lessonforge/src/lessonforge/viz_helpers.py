def get_smart_asset(keyword: str, color=WHITE, height: float = 1.5) -> Mobject:
    """
    Highly resilient, cascading multi-API retrieval engine that fetches SVG assets
    on the fly for Manim rendering. Includes local caching and adaptive native fallbacks.
    """
    color = _resolve_color(color)

    # 0. A pre-resolved LOCAL FILE. The server rewrites an element's content to an
    # absolute .svg path when it generated the icon itself (app/asset_gen.py, the
    # last tier of the cascade) — same contract as fetch_real_image's pre-resolved
    # paths. Checked before normalization: a path is not a keyword to slugify.
    _direct = (keyword or "").strip()
    if _direct.lower().endswith(".svg") and os.path.isabs(_direct) and os.path.exists(_direct):
        try:
            _sanitize_svg_for_manim(_direct)
            svg_mob = SVGMobject(_direct)
            svg_mob.set_color(color)
            svg_mob.scale_to_fit_height(height)
            if svg_mob.width > 12.0:
                svg_mob.scale_to_fit_width(12.0)
            if svg_mob.height > 6.5:
                svg_mob.scale_to_fit_height(6.5)
            return svg_mob
        except Exception as e:
            print(f"Pre-resolved SVG {_direct} failed to load: {e}")

    # Normalize STEM vocabulary to icon-registry-friendly keywords
    keyword_clean = _normalize_svg_keyword(keyword.strip())
    safe_name = "".join([c if c.isalnum() else "_" for c in keyword_clean])
    
    helper_dir = os.path.dirname(os.path.abspath(__file__))
    if os.path.basename(helper_dir) == "temp_renders":
        temp_dir = helper_dir
    else:
        temp_dir = _workspace("temp_renders") or os.path.join(helper_dir, "temp_renders")
    os.makedirs(temp_dir, exist_ok=True)
    local_path = os.path.join(temp_dir, f"asset_{safe_name}.svg")
    
    # 1. Check Local cache
    if os.path.exists(local_path):
        try:
            _sanitize_svg_for_manim(local_path)
            svg_mob = SVGMobject(local_path)
            svg_mob.set_color(color)
            svg_mob.scale_to_fit_height(height)
            if svg_mob.width > 12.0:
                svg_mob.scale_to_fit_width(12.0)
            if svg_mob.height > 6.5:
                svg_mob.scale_to_fit_height(6.5)
            return svg_mob
        except Exception:
            try:
                os.remove(local_path)
            except Exception:
                pass

    # 2. Determine Domain Routing priorities
    is_chem = False
    if len(keyword_clean) > 3 and all(c in "CcnNoOsSpPFFClBrIBH1234567890()=#-/\\[]@+ " for c in keyword_clean):
        is_chem = True
    elif any(t in keyword_clean.lower() for t in ["benzene", "ethanol", "methane", "water", "glucose", "molecule", "acid", "hydroxide"]):
        is_chem = True
        
    science_terms = ["cycle", "system", "cell", "organ", "skeleton", "muscle", "anatomy", "physics", "diagram", "process", "dna", "rna", "virus", "bacteria", "mitochondria", "circuit", "lens", "ray", "field"]
    is_science = (" " in keyword_clean) or any(t in keyword_clean.lower() for t in science_terms)

    # Compile priority cascade list
    if is_chem:
        priority_routes = [
            ("RDKit", lambda: _try_rdkit(keyword_clean, local_path)),
            ("PubChem", lambda: _try_pubchem(keyword_clean, local_path)),
            ("Iconify", lambda: _try_iconify(keyword_clean, local_path)),
            ("Registries", lambda: _try_registries(keyword_clean, local_path)),
            ("Wikimedia", lambda: _try_wikimedia(keyword_clean, local_path)),
            ("Openverse", lambda: _try_openverse(keyword_clean, local_path))
        ]
    elif is_science:
        priority_routes = [
            ("Wikimedia", lambda: _try_wikimedia(keyword_clean, local_path)),
            ("Openverse", lambda: _try_openverse(keyword_clean, local_path)),
            ("Iconify", lambda: _try_iconify(keyword_clean, local_path)),
            ("Registries", lambda: _try_registries(keyword_clean, local_path)),
            ("PubChem", lambda: _try_pubchem(keyword_clean, local_path))
        ]
    else:
        priority_routes = [
            ("Iconify", lambda: _try_iconify(keyword_clean, local_path)),
            ("Registries", lambda: _try_registries(keyword_clean, local_path)),
            ("Wikimedia", lambda: _try_wikimedia(keyword_clean, local_path)),
            ("Openverse", lambda: _try_openverse(keyword_clean, local_path)),
            ("PubChem", lambda: _try_pubchem(keyword_clean, local_path))
        ]
        
    # Execute Cascade
    for name, route_fn in priority_routes:
        if route_fn():
            try:
                _sanitize_svg_for_manim(local_path)
                svg_mob = SVGMobject(local_path)
                svg_mob.set_color(color)
                svg_mob.scale_to_fit_height(height)
                if svg_mob.width > 12.0:
                    svg_mob.scale_to_fit_width(12.0)
                if svg_mob.height > 6.5:
                    svg_mob.scale_to_fit_height(6.5)
                return svg_mob
            except Exception as e:
                print(f"Failed to load SVG from {name} result: {e}")
                try:
                    os.remove(local_path)
                except Exception:
                    pass

    # 3. Fallback: Adaptive Native VGroup
    return generate_adaptive_native_fallback(keyword_clean, color, height)


