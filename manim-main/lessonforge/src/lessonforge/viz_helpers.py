"""Reusable Manim diagram helpers for AI-generated STEM scenes.

Import with `from viz_helpers import *` and COMPOSE these instead of hand-coding raw shapes,
so even lighter LLMs produce rich, correct diagrams. Every function returns a Manim mobject
(usually a VGroup) that you can position (.move_to / .next_to / .to_edge) and animate
(Create, FadeIn, Transform, ReplacementTransform).

Examples
--------
H2 molecule:        molecule(atom("H", WHITE), atom("H", WHITE))
Water (H-O-H):      molecule(atom("H", WHITE), atom("O", RED), atom("H", WHITE))
Show "2 H2":        count_row(lambda: molecule(atom("H", WHITE), atom("H", WHITE)), 2)
Force arrow:        vector(LEFT*2, RIGHT*2, color=YELLOW, label="F")
Label a shape:      labeled(Circle(), "nucleus", direction=DOWN)
"""

