# ── Camera language: semantic spotlight ─────────────────────────────────────────
#
# The probe-safe half of "camera language". True camera moves (zoom/pan via
# MovingCameraScene) are deliberately NOT implemented: the layout probe's
# clipped-text check measures against a FIXED config.frame_width/height, so a moving
# camera would make it report legitimate off-frame content as clipped and miss real
# clipping. Dimming changes opacity, not geometry, so every probe invariant survives.
def spotlight_on(scene, target, dim=0.25, run_time=0.5):
    """Dim every on-screen mobject except `target` (and its family).

    Saves each dimmed mobject's own fill/stroke opacity so spotlight_off restores
    what was there rather than flattening everything to 1.0 — a shape drawn
    deliberately semi-transparent must come back semi-transparent.
    """
    try:
        family = set(id(m) for m in target.get_family())
    except Exception:  # noqa: BLE001 - a bare mobject without a family is fine
        family = {id(target)}
    saved, anims = [], []
    for m in list(getattr(scene, "mobjects", [])):
        if id(m) in family:
            continue
        try:
            saved.append((m, m.get_fill_opacity(), m.get_stroke_opacity()))
            anims.append(m.animate.set_opacity(dim))
        except Exception:  # noqa: BLE001 - never let an effect break a render
            continue
    scene._spotlight_saved = saved
    if anims:
        scene.play(*anims, run_time=run_time)


def spotlight_off(scene, run_time=0.4):
    """Restore the opacities saved by the matching spotlight_on. No-op if unpaired."""
    saved = getattr(scene, "_spotlight_saved", []) or []
    anims = []
    for m, fill_op, stroke_op in saved:
        try:
            anims.append(m.animate.set_fill(opacity=fill_op).set_stroke(opacity=stroke_op))
        except Exception:  # noqa: BLE001
            continue
    scene._spotlight_saved = []
    if anims:
        scene.play(*anims, run_time=run_time)





# ── Sustained motion: the beat filler ───────────────────────────────────────────
#
# Why this exists. A cue is emitted as
#     with self.voiceover(text=...) as tracker:
#         self.play(<entrances>, run_time=tracker.duration * 0.5)
#         <a few 0.4s event animations>
# and then the block ends — manim_voiceover holds the LAST FRAME for whatever audio
# is left. Measured on real boards: entrances and events cover 2-3s of an 8-12s
# narration, so most of every video is a still image. The storyboards don't rescue
# it either: across three live boards the model emitted 92 `show`, 42 `hide`, 6
# `highlight` and ZERO transform/move_to/focus events (2026-08-14) — "no dynamic
# motion in the generated video", as reported.
#
# So motion is CODE's job, not the model's (the house rule). `sustain` spends the
# leftover narration time walking the viewer's eye across the elements just
# introduced — which is also the pedagogically right thing: the emphasis lands on
# whatever is being talked about.
#
# Every gesture is DELIBERATELY round-trip: it returns each mobject to its exact
# starting geometry. The layout probe measures overlap/clipping after every
# self.play, so a gesture that left something displaced would manufacture
# violations and send the repair agent chasing ghosts.

_SUSTAIN_MIN = 1.4     # below this, just hold the frame — a gesture would look twitchy
_GESTURE_RT = 0.85     # one gesture's run_time
_GESTURE_GAP = 0.3     # breathing room after a gesture


def emphasize(mob, run_time=0.5):
    """Draw attention to `mob` WITHOUT recolouring it — a round-trip scale pulse.

    Replaces `Indicate` everywhere the pipeline used to emphasise something
    (2026-08-15, user review: "remove the object highlight"). Indicate recolours
    its target to a flat accent for the duration, which on a themed frame reads as
    the object changing meaning, and on an ImageMobject paints the whole bitmap.

    Round-trip like every sustain gesture: the layout probe measures after each
    self.play, so an emphasis that left the object displaced or resized would
    manufacture violations and send the repair agent chasing ghosts. Returns an
    Animation so callers can `self.play(emphasize(x))` exactly as before.
    """
    # ScaleInPlace + there_and_back is exactly what Indicate does internally, minus
    # the `target.set_color(...)` line. Do NOT build this as two chained `.animate`
    # legs: `.animate` snapshots its target when the animation is CONSTRUCTED, so a
    # `scale(1/1.08)` return leg is computed from the ORIGINAL geometry rather than
    # from the enlarged state, and the pulse settles at 0.926x instead of 1.0
    # (measured drift 0.028 — enough to trip the probe it is supposed to respect).
    from manim.utils.rate_functions import there_and_back

    return ScaleInPlace(mob, 1.08, rate_func=there_and_back,
                        run_time=max(0.2, float(run_time)))


def _sustain_gesture(scene, mob, idx, accent=None, run_time=0.85):
    """One round-trip gesture on `mob`. Returns True if something was played.

    Chosen by index so a multi-element beat cycles through different gestures
    instead of pulsing the same way N times. All three are GEOMETRIC: the colour
    pulse was removed with the rest of the highlight flash, which also retires the
    old "ImageMobject has no colour API" special case — every gesture now works on
    every mobject. `accent` is accepted and ignored so scripts emitted before the
    change still run.
    """
    try:
        if idx % 3 == 0:
            # A sideways nudge — complements the vertical lift below.
            scene.play(mob.animate.shift(RIGHT * 0.12), run_time=run_time * 0.5)
            scene.play(mob.animate.shift(LEFT * 0.12), run_time=run_time * 0.5)
        elif idx % 3 == 1:
            # A lift and settle: bounded, symmetric, ends exactly where it began.
            scene.play(mob.animate.shift(UP * 0.12), run_time=run_time * 0.5)
            scene.play(mob.animate.shift(DOWN * 0.12), run_time=run_time * 0.5)
        else:
            scene.play(mob.animate.scale(1.05), run_time=run_time * 0.5)
            scene.play(mob.animate.scale(1 / 1.05), run_time=run_time * 0.5)
        return True
    except Exception as e:  # noqa: BLE001 — a decoration must never kill a render
        print(f"sustain: gesture skipped ({e})")
        return False


def sustain(scene, mobjects, tracker=None, seconds=None, accent=None):
    """Fill the rest of a narration beat with attention-directing motion.

    `tracker` is the manim_voiceover tracker of the enclosing block; the remaining
    audio time is re-read from it after every gesture, so the animation can never
    outrun the narration (and never truncates it — the block still waits for the
    audio either way). Pass `seconds` instead when there is no tracker.

    Falls back to a plain wait whenever there is nothing to animate, too little time
    left, or anything at all goes wrong.
    """
    def _left():
        if tracker is not None:
            try:
                return max(0.0, float(tracker.get_remaining_duration()))
            except Exception:  # noqa: BLE001 — older/other trackers
                pass
        return max(0.0, float(seconds or 0.0))

    left = _left()
    live = []
    for m in (mobjects or []):
        try:
            if m is not None and m in scene.mobjects:
                live.append(m)
        except Exception:  # noqa: BLE001
            continue
    if not live or left < _SUSTAIN_MIN:
        if left > 0:
            scene.wait(left)
        return

    idx = 0
    while left >= _SUSTAIN_MIN and idx < len(live) * 3:
        mob = live[idx % len(live)]
        rt = min(_GESTURE_RT, max(0.4, left - _GESTURE_GAP - 0.4))
        if not _sustain_gesture(scene, mob, idx, accent, rt):
            break
        idx += 1
        left = _left() if tracker is not None else left - (rt + _GESTURE_GAP)
        if left > _GESTURE_GAP:
            scene.wait(_GESTURE_GAP)
            left = _left() if tracker is not None else left - _GESTURE_GAP
    if left > 0:
        scene.wait(left)
