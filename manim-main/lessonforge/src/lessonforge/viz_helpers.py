def _try_rdkit(keyword: str, local_path: str) -> bool:
    try:
        from rdkit import Chem
        mol = Chem.MolFromSmiles(keyword)
        if mol is not None:
            from rdkit.Chem import rdDepictor
            from rdkit.Chem.Draw import rdMolDraw2D
            rdDepictor.Compute2DCoords(mol)
            drawer = rdMolDraw2D.MolDraw2DSVG(500, 500)
            options = drawer.drawOptions()
            options.clearBackground = True
            options.setBackgroundColour((0, 0, 0, 0))
            options.bondLineWidth = 3
            options.minFontSize = 40
            drawer.DrawMolecule(mol)
            drawer.FinishDrawing()
            svg_code = drawer.GetDrawingText()
            with open(local_path, "w", encoding="utf-8") as f:
                f.write(svg_code)
            return True
    except Exception as e:
        print(f"RDKit local render failed: {e}")
    return False


def _try_pubchem(keyword: str, local_path: str) -> bool:
    try:
        is_smiles = False
        if len(keyword) > 3 and all(c in "CcnNoOsSpPFFClBrIBH1234567890()=#-/\\[]@+ " for c in keyword):
            is_smiles = True
        
        encoded = urllib.parse.quote(keyword)
        id_type = "smiles" if is_smiles else "name"
        url = f"https://pubchem.ncbi.nlm.nih.gov/rest/pug/compound/{id_type}/{encoded}/record/SVG"
        res = requests.get(url, headers=_REQ_HEADERS, timeout=5)
        if res.status_code == 200 and "</svg>" in res.text:
            with open(local_path, "w", encoding="utf-8") as f:
                f.write(res.text)
            return True
    except Exception as e:
        print(f"PubChem fetch failed: {e}")
    return False


def _try_wikimedia(keyword: str, local_path: str) -> bool:
    try:
        search_query = f"{keyword} filetype:svg"
        encoded_query = urllib.parse.quote(search_query)
        search_url = f"https://commons.wikimedia.org/w/api.php?action=query&list=search&srsearch={encoded_query}&format=json&utf8=1"
        res = requests.get(search_url, headers=_REQ_HEADERS, timeout=5)
        res.raise_for_status()
        search_results = res.json().get("query", {}).get("search", [])
        if not search_results:
            return False
            
        first_title = search_results[0]["title"]
        encoded_title = urllib.parse.quote(first_title)
        
        info_url = f"https://commons.wikimedia.org/w/api.php?action=query&titles={encoded_title}&prop=imageinfo&iiprop=url&format=json"
        info_res = requests.get(info_url, headers=_REQ_HEADERS, timeout=5).json()
        pages = info_res.get("query", {}).get("pages", {})
        
        svg_url = None
        for page_id, page_data in pages.items():
            imageinfo = page_data.get("imageinfo", [])
            if imageinfo:
                svg_url = imageinfo[0].get("url")
                break
                
        if not svg_url or not svg_url.lower().endswith(".svg"):
            return False
            
        svg_response = requests.get(svg_url, headers=_REQ_HEADERS, timeout=5)
        svg_response.raise_for_status()
        svg_code = svg_response.text
        if "</svg>" in svg_code:
            with open(local_path, "w", encoding="utf-8") as f:
                f.write(svg_code)
            return True
    except Exception as e:
        print(f"Wikimedia fetch failed: {e}")
    return False


