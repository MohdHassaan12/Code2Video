def _normalize_svg_keyword(keyword: str) -> str:
    """Map STEM vocabulary to icon-registry-friendly search terms."""
    kl = keyword.lower().strip()
    if kl in _SVG_KEYWORD_NORM:
        return _SVG_KEYWORD_NORM[kl]
    # Partial match — find longest matching key
    best, best_len = None, 0
    for k, v in _SVG_KEYWORD_NORM.items():
        if k in kl and len(k) > best_len:
            best, best_len = v, len(k)
    return best if best else keyword

