"""Render the chapters, join them, and record what was actually checked.

    lesson.json ──▶ audio.build_audio ──▶ timeline.json ─┐
    chapters_*.py (hand-written or generated scenes) ────┼─▶ render_chapters ─▶ assemble ─▶ run_checks
    (chapters with no scene get an animatic) ────────────┘

Layout of a lesson directory (everything below ``lesson.json`` and the scene files is
generated and safe to delete):

    lesson.json  chapters_*.py
    timeline.json  audio_report.json  audio/  media/  logs/
    output/<slug>.mp4  captions.vtt  chapters.ffmeta  chapter_NN_audit.json
           media_probe.json  final_checks.json  review.html

Rules carried over from the first long-form build, each learned the hard way:
every chapter renders in its OWN media directory (concurrent manim jobs race on
shared temporary LaTeX/SVG files), a finished process exit is not acceptance (the
checks read the encoded file back), and the report states its own limits.
"""
from __future__ import annotations

import concurrent.futures
import json
import os
import re
import shutil
import subprocess
import sys
from pathlib import Path

from .. import knobs, layout_probe
from .contract import Lesson, load_lesson

QUALITY_DIRS = {"l": "480p", "m": "720p", "h": "1080p", "p": "1440p", "k": "2160p"}
_SCENE_CLASS = re.compile(r"^class\s+(C\d{2,})\s*\(", re.M)
_BEAT_MARK = re.compile(r"LESSON_BEAT:\s*(\S+)")
AUTO_SCENES = "_auto_chapters.py"


#: Seconds one chapter's render may take before it is stopped (a 60-second chapter with a heavy scene took
#: 7.5 minutes at 720p on a busy machine). ``LESSONFORGE_RENDER_TIMEOUT`` changes it.
RENDER_TIMEOUT = int(os.getenv("LESSONFORGE_RENDER_TIMEOUT", "3600"))


def slugify(text: str) -> str:
    return re.sub(r"[^a-z0-9]+", "_", text.lower()).strip("_") or "lesson"


def find_scenes(lesson_dir: Path, lesson: Lesson) -> dict[str, Path]:
    """Map each chapter's scene class (C01, …) to the file that defines it.

    ``lesson.json`` may pin this with ``"scenes": {"C05": "chapters_rest.py"}`` — useful
    when drafts of the same chapter sit side by side. Otherwise the scene files are
    scanned; a class defined twice is an error, not a coin toss.
    """
    pinned = {name: lesson_dir / rel for name, rel in (getattr(lesson, "scenes", None) or {}).items()}
    found: dict[str, Path] = dict(pinned)
    for script in sorted(lesson_dir.glob("*.py")):
        if script.name == AUTO_SCENES:
            continue
        for name in _SCENE_CLASS.findall(script.read_text(encoding="utf-8")):
            if name in pinned:
                continue
            if name in found:
                raise ValueError(f"{name} is defined in both {found[name].name} and {script.name}; "
                                 f'pin one with "scenes" in lesson.json')
            found[name] = script
    return found


def write_auto_scenes(lesson_dir: Path, lesson: Lesson, missing: list[int]) -> Path:
    """Animatic scenes for chapters with no scene code (see runtime.AutoChapter)."""
    lines = ['"""Generated by lessonforge: animatics for chapters without a hand-written scene.',
             'Regenerated on every build — do not edit; write a real C## scene instead."""',
             "from lessonforge.longform.runtime import *  # noqa: F401,F403", ""]
    for chapter_id in missing:
        # Beats that carry ``steps`` are complete instructions (GuidedChapter); a bare
        # script only gets a placeholder card (AutoChapter).
        guided = any(getattr(b, "steps", None) for b in lesson.chapter(chapter_id).beats)
        base = "GuidedChapter" if guided else "AutoChapter"
        lines += ["", f"class C{chapter_id:02}({base}):", f"    chapter_id = {chapter_id}", ""]
    path = lesson_dir / AUTO_SCENES
    path.write_text("\n".join(lines), encoding="utf-8")
    return path


def _attribute_layout(log_text: str) -> list[dict]:
    """Probe findings from a render log, each tagged with the beat it occurred in."""
    findings, beat = [], None
    for line in log_text.splitlines():
        mark = _BEAT_MARK.search(line)
        if mark:
            beat = mark.group(1)
            continue
        for found in layout_probe.parse(line):
            findings.append({"beat": beat, **found})
    return findings


def find_renderer_ts_dir() -> Path | None:
    env_dir = os.environ.get("LESSONFORGE_RENDERER_TS_DIR")
    if env_dir and Path(env_dir).exists():
        return Path(env_dir).resolve()
    cand = Path(__file__).resolve().parents[4] / "renderer-ts"
    if cand.exists():
        return cand
    return None


def render_chapters_ts(lesson_dir: str | Path, lesson: Lesson | None = None, quality: str = "h",
                       fps: int = 30, jobs: int = 4, only: list[int] | None = None, log=print,
                       extra_env: dict[str, str] | None = None) -> dict[int, Path]:
    """Render chapters via renderer-ts (TypeScript/Revideo). Returns chapter id → mp4."""
    root = Path(lesson_dir).resolve()
    lesson = lesson or load_lesson(root)
    if not (root / "timeline.json").exists():
        raise FileNotFoundError("timeline.json missing — build the audio first (lessonforge lesson audio)")
    ts_dir = find_renderer_ts_dir()
    if not ts_dir:
        raise RuntimeError("renderer-ts directory not found. Set LESSONFORGE_RENDERER_TS_DIR or check repo structure.")

    (root / "logs").mkdir(exist_ok=True)
    (root / "output").mkdir(exist_ok=True)

    w = 854 if quality == "l" else (1280 if quality == "m" else 1920)
    h = 480 if quality == "l" else (720 if quality == "m" else 1080)
    if quality not in ("l", "h"):
        w, h = 1280, 720

    timeline_data = json.loads((root / "timeline.json").read_text(encoding="utf-8"))
    audio_path = (root / "audio" / "narration.wav").resolve()
    env = {**os.environ, **(extra_env or {})}

    def render(chapter) -> tuple[int, Path | None, str]:
        name = chapter.scene_name
        ids = {b.id for b in chapter.beats}
        chap_timeline = [t for t in timeline_data if t.get("id") in ids]
        input_data = {
            "version": 1,
            "title": lesson.title,
            "chapter": {"id": chapter.id, "title": chapter.title, "beats": [b.model_dump() for b in chapter.beats]},
            "timeline": chap_timeline,
            "audio": str(audio_path) if audio_path.exists() else None,
            "width": w,
            "height": h,
            "fps": fps,
        }
        input_path = root / "output" / f"render_input_{name}.json"
        input_path.write_text(json.dumps(input_data, indent=1), encoding="utf-8")

        out_dir = root / "media" / name / "videos" / "ts" / f"{h}p{fps}"
        out_dir.mkdir(parents=True, exist_ok=True)
        out_file = out_dir / f"{name}.mp4"

        cmd = ["node", "scripts/render.mjs", str(input_path), str(out_file)]
        try:
            proc = subprocess.run(cmd, capture_output=True, text=True, env=env, cwd=ts_dir, timeout=RENDER_TIMEOUT)
        except subprocess.TimeoutExpired as late:
            def said(part):
                return part.decode("utf-8", "replace") if isinstance(part, bytes) else (part or "")
            text = said(late.stdout) + said(late.stderr) + f"\nLESSON_NOTE: the render of {name} was stopped after {RENDER_TIMEOUT} s without finishing\n"
            (root / "logs" / f"{name}.log").write_text(text, encoding="utf-8")
            return chapter.id, None, text

        text = (proc.stdout or "") + (proc.stderr or "")
        (root / "logs" / f"{name}.log").write_text(text, encoding="utf-8")
        if proc.returncode != 0 or not out_file.exists():
            return chapter.id, None, text

        audit_path = root / "output" / f"chapter_{chapter.id:02}_audit.json"
        if audit_path.exists():
            audit = json.loads(audit_path.read_text(encoding="utf-8"))
            audit["scene_file"] = "renderer-ts"
            audit_path.write_text(json.dumps(audit, indent=2), encoding="utf-8")
        return chapter.id, out_file, text

    chapters = [c for c in lesson.chapters if not only or c.id in only]
    clips: dict[int, Path] = {}
    failures = []
    with concurrent.futures.ThreadPoolExecutor(max_workers=max(1, jobs)) as pool:
        for chapter_id, clip, text in pool.map(render, chapters):
            if clip is None:
                failures.append(chapter_id)
                tail = "\n".join(text.strip().splitlines()[-12:])
                log(f"[render] chapter {chapter_id:02} FAILED (ts) — see logs/C{chapter_id:02}.log\n{tail}")
            else:
                clips[chapter_id] = clip
                log(f"[render] chapter {chapter_id:02} ok (ts) → {clip.relative_to(root)}")
    if failures:
        raise RuntimeError(f"chapter render failed: {failures}")
    return clips


def render_chapters(lesson_dir: str | Path, lesson: Lesson | None = None, quality: str = "h",
                    fps: int = 30, jobs: int = 4, only: list[int] | None = None, log=print,
                    extra_env: dict[str, str] | None = None,
                    renderer: str | None = None) -> dict[int, Path]:
    """Render every chapter (parallel, isolated media dirs). Returns chapter id → mp4."""
    use_renderer = (renderer or knobs.get("LESSONFORGE_RENDERER", "manim") or "manim").strip().lower()
    if use_renderer in ("ts", "revideo"):
        return render_chapters_ts(lesson_dir, lesson=lesson, quality=quality, fps=fps, jobs=jobs,
                                  only=only, log=log, extra_env=extra_env)

    root = Path(lesson_dir).resolve()
    lesson = lesson or load_lesson(root)
    if not (root / "timeline.json").exists():
        raise FileNotFoundError("timeline.json missing — build the audio first (lessonforge lesson audio)")
    scenes = find_scenes(root, lesson)
    missing = [c.id for c in lesson.chapters if c.scene_name not in scenes]
    if missing:
        auto = write_auto_scenes(root, lesson, missing)
        scenes.update({f"C{i:02}": auto for i in missing})
        log(f"[render] no scene code for chapter(s) {missing} — rendering animatics")
    (root / "logs").mkdir(exist_ok=True)
    (root / "output").mkdir(exist_ok=True)
    env = {**os.environ, "LESSONFORGE_LESSON_DIR": str(root), **(extra_env or {})}

    def render(chapter) -> tuple[int, Path | None, str]:
        name, script = chapter.scene_name, scenes[chapter.scene_name]
        media = root / "media" / name
        cmd = [sys.executable, "-m", "manim", f"-q{quality}", "--fps", str(fps),
               "--media_dir", str(media), str(script), name]
        def clean_partial_cache():
            try:
                for p in media.glob("videos/**/partial_movie_files"):
                    if p.is_dir():
                        shutil.rmtree(p, ignore_errors=True)
                for f in media.glob(f"videos/*/*/{name}.mp4"):
                    f.unlink(missing_ok=True)
            except Exception:
                pass

        try:
            proc = subprocess.run(cmd, capture_output=True, text=True, env=env, cwd=root, timeout=RENDER_TIMEOUT)
        except subprocess.TimeoutExpired as late:
            # A render that does not end is ended here (the child is killed by ``run``). Without a limit a
            # stuck chapter kept its job "rendering" for good.
            clean_partial_cache()
            def said(part):
                return part.decode("utf-8", "replace") if isinstance(part, bytes) else (part or "")
            text = said(late.stdout) + said(late.stderr) + f"\nLESSON_NOTE: the render of {name} was stopped after {RENDER_TIMEOUT} s without finishing\n"
            (root / "logs" / f"{name}.log").write_text(text, encoding="utf-8")
            return chapter.id, None, text
        text = (proc.stdout or "") + (proc.stderr or "")
        (root / "logs" / f"{name}.log").write_text(text, encoding="utf-8")
        clips = sorted(media.glob(f"videos/*/*/{name}.mp4"), key=lambda p: p.stat().st_mtime)
        if proc.returncode != 0 or not clips:
            clean_partial_cache()
            return chapter.id, None, text
        audit_path = root / "output" / f"chapter_{chapter.id:02}_audit.json"
        if audit_path.exists():
            audit = json.loads(audit_path.read_text(encoding="utf-8"))
            audit["layout"] = _attribute_layout(text)
            audit["scene_file"] = script.name
            audit["animatic"] = script.name == AUTO_SCENES and not any(
                getattr(b, "steps", None) for b in chapter.beats)
            audit_path.write_text(json.dumps(audit, indent=2), encoding="utf-8")
        return chapter.id, clips[-1], text

    chapters = [c for c in lesson.chapters if not only or c.id in only]
    clips: dict[int, Path] = {}
    failures = []
    with concurrent.futures.ThreadPoolExecutor(max_workers=max(1, jobs)) as pool:
        for chapter_id, clip, text in pool.map(render, chapters):
            if clip is None:
                failures.append(chapter_id)
                tail = "\n".join(text.strip().splitlines()[-12:])
                log(f"[render] chapter {chapter_id:02} FAILED — see logs/C{chapter_id:02}.log\n{tail}")
            else:
                clips[chapter_id] = clip
                log(f"[render] chapter {chapter_id:02} ok → {clip.relative_to(root)}")
    if failures:
        raise RuntimeError(f"chapter render failed: {failures}")
    return clips


def find_clips(lesson_dir: str | Path, lesson: Lesson) -> dict[int, Path]:
    """Chapter clips already rendered under ``media/`` (newest per chapter)."""
    root, clips = Path(lesson_dir).resolve(), {}
    for chapter in lesson.chapters:
        ch_media = root / "media" / chapter.scene_name
        found = sorted(ch_media.glob(f"videos/*/*/{chapter.scene_name}.mp4"),
                       key=lambda p: p.stat().st_mtime)
        if not found:
            found = sorted(ch_media.glob(f"**/{chapter.scene_name}.mp4"),
                           key=lambda p: p.stat().st_mtime)
        if not found:
            raise FileNotFoundError(f"chapter {chapter.id} has not been rendered (lessonforge lesson render)")
        clips[chapter.id] = found[-1]
    return clips


def _run(cmd: list[str]) -> None:
    subprocess.run(cmd, check=True)


def assemble(lesson_dir: str | Path, clips: dict[int, Path], lesson: Lesson | None = None, log=print) -> Path:
    """Concatenate the chapters and mux narration, captions and chapter markers."""
    root = Path(lesson_dir).resolve()
    lesson = lesson or load_lesson(root)
    out = root / "output"
    timeline = json.loads((root / "timeline.json").read_text(encoding="utf-8"))
    ordered = [clips[c.id] for c in lesson.chapters]

    concat = out / "concat.txt"
    concat.write_text("".join("file '" + str(p.resolve()).replace("'", "'\\''") + "'\n" for p in ordered),
                      encoding="utf-8")
    meta = [";FFMETADATA1", f"title={lesson.title}", "artist=lessonforge; synthetic narration"]
    for chapter in lesson.chapters:
        beats = [t for t in timeline if t["chapter"] == chapter.id]
        meta += ["[CHAPTER]", "TIMEBASE=1/1000", f"START={round(beats[0]['start'] * 1000)}",
                 f"END={round((beats[-1]['start'] + beats[-1]['duration']) * 1000)}", f"title={chapter.title}"]
    (out / "chapters.ffmeta").write_text("\n".join(meta), encoding="utf-8")

    video = out / f"{slugify(lesson.title)}.mp4"
    language = (lesson.language or "en").split("-")[0]
    _run(["ffmpeg", "-v", "error", "-y",
          "-f", "concat", "-safe", "0", "-i", str(concat),
          "-i", str(root / "audio" / "narration.wav"),
          "-i", str(out / "captions.vtt"),
          "-i", str(out / "chapters.ffmeta"),
          "-map", "0:v:0", "-map", "1:a:0", "-map", "2:s:0", "-map_metadata", "3", "-map_chapters", "3",
          "-c:v", "copy", "-af", "loudnorm=I=-18:TP=-1.5:LRA=11", "-ar", "48000", "-c:a", "aac", "-b:a", "192k",
          "-c:s", "mov_text", "-metadata:s:s:0", f"language={language}",
          "-movflags", "+faststart", str(video)])
    probe = json.loads(subprocess.check_output(
        ["ffprobe", "-v", "error", "-show_format", "-show_streams", "-show_chapters", "-of", "json", str(video)]))
    (out / "media_probe.json").write_text(json.dumps(probe, indent=2), encoding="utf-8")
    log(f"[assemble] {video.relative_to(root)} ({float(probe['format']['duration']):.1f}s)")
    return video


def run_checks(lesson_dir: str | Path, video: Path, lesson: Lesson | None = None,
               quality: str = "h", fps: int = 30, decode: bool = True, log=print) -> dict:
    """Read the finished file and the audits back; write ``output/final_checks.json``.

    Nothing here raises on a failed check: every check is recorded with its result so
    a failing build still leaves a complete report. ``status`` is the summary.
    """
    root = Path(lesson_dir).resolve()
    lesson = lesson or load_lesson(root)
    out = root / "output"
    timeline = json.loads((root / "timeline.json").read_text(encoding="utf-8"))
    probe = json.loads((out / "media_probe.json").read_text(encoding="utf-8"))
    expected = sum(t["duration"] for t in timeline)
    checks: list[dict] = []

    def check(name: str, ok: bool, detail: str = "") -> None:
        checks.append({"check": name, "passed": bool(ok), "detail": detail})

    streams = {s["codec_type"]: s for s in probe["streams"]}
    duration = float(probe["format"]["duration"])
    video_stream = streams.get("video", {})
    check("duration matches the timeline", abs(duration - expected) < 0.2,
          f"file {duration:.3f}s, timeline {expected:.3f}s")
    height = int(video_stream.get("height", 0))
    check("resolution matches the requested quality", f"{height}p" == QUALITY_DIRS.get(quality, f"{height}p"),
          f"{video_stream.get('width')}x{height}")
    check("frame rate", video_stream.get("r_frame_rate") == f"{fps}/1", str(video_stream.get("r_frame_rate")))
    check("audio stream present", "audio" in streams)
    check("subtitle stream present", "subtitle" in streams)
    check("one chapter marker per chapter", len(probe.get("chapters", [])) == len(lesson.chapters),
          f"{len(probe.get('chapters', []))} of {len(lesson.chapters)}")

    def seconds(stamp: str) -> float:
        h, m, s = stamp.split(":")
        return int(h) * 3600 + int(m) * 60 + float(s)

    spans = re.findall(r"(\d\d:\d\d:\d\d\.\d{3}) --> (\d\d:\d\d:\d\d\.\d{3})",
                       (out / "captions.vtt").read_text(encoding="utf-8"))
    ordered, previous = True, 0.0
    for start, end in spans:
        start, end = seconds(start), seconds(end)
        ordered &= start >= previous - 0.002 and start < end <= expected + 0.002
        previous = end
    check("captions are ordered and inside the video", ordered and bool(spans), f"{len(spans)} cues")

    audits = {}
    for chapter in lesson.chapters:
        path = out / f"chapter_{chapter.id:02}_audit.json"
        if path.exists():
            audits[chapter.id] = json.loads(path.read_text(encoding="utf-8"))
    check("every chapter wrote an audit", len(audits) == len(lesson.chapters),
          f"{len(audits)} of {len(lesson.chapters)}")
    beat_ends = sum(len(a["bounds"]) for a in audits.values())
    check("every beat reached its end-of-beat bounds check", beat_ends == len(timeline),
          f"{beat_ends} of {len(timeline)}")
    bounds = [(cid, b["beat"], v) for cid, a in audits.items() for b in a["bounds"] for v in b["bounds_violations"]]
    check("nothing outside the stage at any beat end", not bounds, f"{len(bounds)} violation(s)")
    layout = [(cid, f) for cid, a in audits.items() for f in a.get("layout", [])]
    counted = [f for _, f in layout if f["counted"]]
    check("no text overlap / clipping / strike-through after any play", not counted,
          f"{len(counted)} counted, {len(layout) - len(counted)} reported-only")
    cues = [c for a in audits.values() for c in a["cues"]]
    # Against the SPOKEN word ("anchor"); the picture is scheduled a little before it.
    late = [c["actual_before_wait"] - c.get("anchor", c["target"]) for c in cues]
    worst = max(late, default=0.0)
    check("no cue fired more than 0.5s after its spoken anchor", worst <= 0.5, f"worst lateness {worst:.2f}s")

    if decode:
        proc = subprocess.run(["ffmpeg", "-v", "error", "-i", str(video), "-f", "null", "-"],
                              capture_output=True, text=True)
        check("full decode of the finished file", proc.returncode == 0 and not proc.stderr.strip(),
              proc.stderr.strip()[:200])

    sentences = [s for t in timeline for s in t["sentences"]]
    animatics = sorted(cid for cid, a in audits.items() if a.get("animatic"))
    report = {
        "status": "technical_checks_passed" if all(c["passed"] for c in checks) else "technical_checks_failed",
        "video": video.name,
        "duration_seconds": duration,
        "resolution": [video_stream.get("width"), video_stream.get("height")],
        "fps": fps,
        "chapters": len(lesson.chapters),
        "beats": len(timeline),
        "captions": len(spans),
        "animation_anchors": len(cues),
        "anchor_timing": {k: sum(1 for c in cues if c.get("timing_source", "").startswith(k))
                          for k in ("aligned", "word-position")},
        "sentence_timing": {k: sum(1 for s in sentences if s.get("timing_source", "measured") == k)
                            for k in ("aligned", "measured", "pause-snapped", "estimated")},
        "bounds_violations": len(bounds),
        # Where each one is, so a repair can be aimed at its chapter (the count alone could only be reported).
        "bounds_detail": [{"chapter": cid, "beat": beat, "type": v.get("type"), "bbox": v.get("bbox")} for cid, beat, v in bounds],
        "layout_findings": {"counted": len(counted), "reported_only": len(layout) - len(counted),
                            "detail": [{"chapter": cid, **f} for cid, f in layout]},
        "animatic_chapters": animatics,
        "checks": checks,
        "review_limits": [
            "Layout is measured after every play() and at beat ends, not on every frame; "
            "collisions that begin and end inside one animation are not seen.",
            "Positions inside a sentence are word-position estimates unless the timeline carries aligned words.",
            "These are production measurements. They are not teacher approval, a continuous "
            "listening review, or evidence that a learner understands the lesson.",
        ] + (["Chapters " + ", ".join(map(str, animatics)) + " are animatics (no scene code yet)."]
             if animatics else []),
    }
    (out / "final_checks.json").write_text(json.dumps(report, indent=2), encoding="utf-8")
    for c in checks:
        log(f"[check] {'ok  ' if c['passed'] else 'FAIL'} {c['check']}" + (f" — {c['detail']}" if c["detail"] else ""))
    return report


def build(lesson_dir: str | Path, voice: str = "silent", quality: str = "h", fps: int = 30, jobs: int = 4,
          granularity: str = "beat", target_seconds: float | None = None, log=print,
          renderer: str | None = None) -> dict:
    """The whole pipeline: storyboard gate → audio → timeline → chapters → video → checks → QA report.

    A lesson built from its folder is somebody's reviewed file: the storyboard gate REPORTS on it here and changes
    nothing (the harness's jobs repair before speech; ``storyboard.prepare(fix=True)`` does it by hand).
    """
    from . import qa, storyboard, timeline_compiler
    from .audio import BuildOptions, build_audio
    from .review import write_review

    root = Path(lesson_dir).resolve()
    lesson = load_lesson(root)
    raw = json.loads((root / "lesson.json").read_text(encoding="utf-8"))
    storyboard.prepare(root, raw, fix=False, log=log)
    build_audio(lesson, root, voice, BuildOptions(granularity=granularity, fps=fps,
                                                  target_seconds=target_seconds), log=log)
    timeline_compiler.compile_lesson(root, raw, fps=fps, log=log)
    clips = render_chapters(root, lesson, quality=quality, fps=fps, jobs=jobs, log=log, renderer=renderer)
    video = assemble(root, clips, lesson, log=log)
    report = run_checks(root, video, lesson, quality=quality, fps=fps, log=log)
    write_review(root, lesson, video, log=log)
    qa.write_qa(root, log=log)
    qa.write_bundle(root, video, log=log)
    return report
