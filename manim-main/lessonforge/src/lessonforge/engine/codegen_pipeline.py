# Words that describe a primitive rather than a thing. A description made ONLY of these
# tells the renderer what to draw and the viewer nothing at all.
_PRIMITIVE_WORDS = {
    "circle", "circles", "dot", "dots", "point", "points", "square", "squares",
    "rectangle", "rectangles", "box", "line", "lines", "arrow", "arrows", "triangle",
    "polygon", "ellipse", "oval", "ring", "curve", "arc", "shape", "marker",
    # size / style / direction adjectives carry no subject either
    "small", "large", "big", "tiny", "short", "long", "thin", "thick", "horizontal",
    "vertical", "dashed", "dotted", "solid", "filled", "hollow", "left", "right", "up",
    "down", "upward", "downward", "pointing", "a", "an", "the", "and", "of", "with",
}


def _content_free_shapes(scenes):
    """Descriptions of `shape` elements that name a primitive and nothing else."""
    empty = []
    for scene in scenes:
        for el in scene.get("elements") or []:
            if el.get("type") != "shape":
                continue
            text = str(el.get("content") or "").strip().lower()
            words = [w for w in re.findall(r"[a-z]+", text)]
            if words and all(w in _PRIMITIVE_WORDS for w in words):
                empty.append(text[:40])
    return empty


def _log_element_survival(storyboard, asset_warnings):
    """Report how many declared elements will actually DRAW something.

    The counterpart to the screen plan's `[DEEP] objects planned -> elements written`.
    That metric stops at the IR, and the first live run showed why that is not enough:
    a board with 46 elements produced frames carrying a fraction of them, because every
    image had degraded to a Text placeholder of its own search query and three of four
    simulations to bare circles. The IR was rich; the frame was not, and no number
    anywhere said so — the pipeline degrades quietly by design, which is right for one
    bad asset and misleading for a whole tier being down.

    Counting is deliberately crude (a warned element is a degraded element): the point
    is a single honest line per render, not a new subsystem.
    """
    try:
        scenes = storyboard.get("visual_storyboard") or []
        total = sum(len(s.get("elements") or []) for s in scenes)
        if not total:
            return
        warned = {(w.get("scene"), w.get("element_id")) for w in (asset_warnings or [])}
        by_type = {}
        for scene in scenes:
            for el in scene.get("elements") or []:
                key = el.get("type", "?")
                hit = (scene.get("scene_index"), el.get("id")) in warned
                seen, bad = by_type.get(key, (0, 0))
                by_type[key] = (seen + 1, bad + (1 if hit else 0))
        degraded = sum(bad for _, bad in by_type.values())
        detail = ", ".join(f"{k} {n - b}/{n}" for k, (n, b) in sorted(by_type.items()))
        level = logger.warning if degraded else logger.info
        level("[ELEMENTS] %d declared, %d degraded to placeholders — %s",
              total, degraded, detail)

        # A `shape` whose content is a bare primitive name draws a bare primitive: a
        # ring on an empty canvas that means nothing. It carries no asset warning —
        # nothing FAILED — so the count above reports it as healthy while the frame
        # shows a scattering of empty circles (measured on the 2026-08-15 board: 16 of
        # 46 elements were "circle", "point", "arrow pointing right"). Counting it is
        # what tells you whether the SHAPE_CONTENT_RULE prompt change actually landed.
        empty = _content_free_shapes(scenes)
        if empty:
            logger.warning("[ELEMENTS] %d shape(s) name only a primitive and will draw "
                           "an empty mark: %s", len(empty), ", ".join(sorted(set(empty))[:8]))
        # A whole tier failing is a different event from one bad query, and it is the
        # one worth shouting about: it usually means a provider is blocking us, not
        # that the model asked for something obscure.
        for etype, (n, bad) in sorted(by_type.items()):
            if n >= 2 and bad == n:
                logger.warning("[ELEMENTS] EVERY %r element failed to resolve (%d/%d) — "
                               "that is a provider/config problem, not a bad query.",
                               etype, bad, n)
    except Exception as e:                       # never break codegen over a log line
        logger.debug("element survival census skipped: %s", e)


def extract_method_from_code(code, method_name):
    import ast
    try:
        tree = ast.parse(code)
        for node in ast.walk(tree):
            if isinstance(node, ast.FunctionDef) and node.name == method_name:
                import astunparse
                return astunparse.unparse(node)
    except Exception:
        try:
            import ast
            tree = ast.parse(code)
            for node in ast.walk(tree):
                if isinstance(node, ast.FunctionDef) and node.name == method_name:
                    return ast.unparse(node)
        except Exception:
            pass
        pass
    import re
    pattern = rf"def\s+{method_name}\s*\(.*?\):(.*?)(?=\n\s*def\s|\Z)"
    match = re.search(pattern, code, re.DOTALL)
    if match:
        return f"def {method_name}(self):" + match.group(1)
    return ""


